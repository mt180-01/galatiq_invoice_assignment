"""Every provided invoice -> decision, in two separate runs, written to docs/EVALUATION.md.

  rules only   no model at all (--offline)
  LLM on       the recorded live Grok run, replayed offline (docs/live_runs/provided-invoices.cassette.jsonl): the real model's answers, no network, no cost

    python scripts/evaluate.py            # regenerate docs/EVALUATION.md
    python scripts/evaluate.py --check    # fail if the committed file is out of date (it is, if prompts changed since the recording)

Two kinds of label, kept apart: what the brief itself says should happen to eight invoices (independent of this code), and the label for all 17 that the
developer wrote while building it (so it guards regressions but is not an independent test).
"""
from __future__ import annotations

import argparse
import asyncio
import sys
import tempfile
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from acme_ap.metrics import kpis, llm_usage  # noqa: E402
from acme_ap.runner import run_batch  # noqa: E402
from tests.test_pipeline import EXPECTED  # noqa: E402

DATA = ROOT / "data" / "invoices"
CASSETTE = ROOT / "docs" / "live_runs" / "provided-invoices.cassette.jsonl"
OUT = ROOT / "docs" / "EVALUATION.md"
# What docs/ASSIGNMENT.md says should happen, invoice by invoice (the brief's table). Everything else is labelled by the developer.
BRIEF = {"INV-1001": "PAID", "INV-1004": "PAID", "INV-1006": "PAID", "INV-1002": "REJECT", "INV-1003": "REJECT", "INV-1008": "REJECT", "INV-1016": "REJECT", "INV-1009": "REJECT"}
BRIEF_WORDS = {"INV-1001": "within stock, passes", "INV-1004": "within stock, passes", "INV-1006": "within stock, passes", "INV-1002": "stock mismatch flagged",
               "INV-1003": "out of stock / suspicious flagged", "INV-1008": "unknown item flagged", "INV-1016": "unknown item flagged", "INV-1009": "invalid data flagged"}
SHOW = {"PAID": "paid", "REJECT": "rejected", "AWAITING": "to a person", "ESCALATE": "to a person", "SCHEDULED": "scheduled"}


def same(a: str, b: str) -> bool:
    """'Escalated' (no approval service attached) and 'awaiting' (one is) both mean: a person decides."""
    return {"ESCALATE": "AWAITING"}.get(a, a) == {"ESCALATE": "AWAITING"}.get(b, b)


def run(**mode) -> tuple[list, object]:
    with tempfile.TemporaryDirectory() as tmp:
        base = dict(db=str(Path(tmp) / "e.db"), keep_ledger=False, llm_concurrency=8, offline=False, simulate=False, grok=False, no_store=True, sequential=True)  # file order, one at a time: which copy of a duplicate is blocked must not depend on thread timing
        args = SimpleNamespace(**{**base, **mode})
        outs, _, _ = asyncio.run(run_batch([str(p) for p in sorted(DATA.iterdir())], args, 1))
    by_inv = {}
    for o in outs:
        if o.invoice and o.status != "DUPLICATE":
            by_inv[o.invoice.invoice_number + (f"-{o.invoice.revision}" if o.invoice.revision else "")] = o
    return outs, by_inv


def cell(text: str, n: int = 95) -> str:
    text = " ".join(str(text).replace("|", "/").split())
    return text if len(text) <= n else text[:n].rsplit(" ", 1)[0].rstrip(".,;:") + "…"


def model_part(o) -> str:
    """What the model did on this invoice, from its recorded trace."""
    bits = []
    tools = sum(e["kind"] == "tool" for t in o.trace for e in t.get("events", []))
    asked = [e["as"] for t in o.trace for e in t.get("events", []) if e["kind"] == "model"]
    if "intake" in asked:
        bits.append("read the document")
    dec = next((e["text"].split(":")[0] for t in o.trace if t["agent"] == "Reviewer" for e in t.get("events", []) if e["kind"] == "decision"), None)
    if dec:
        bits.append(f"second opinion: {dec}" + (f" ({tools} tool calls)" if tools else ""))
    if "resolver" in asked:
        bits.append("searched for a name fix")
    if o.explanation:
        bits.append("wrote the note")
    if o.followup and any(e["kind"] == "wrote" for t in o.trace if t["action"].startswith("drafted") for e in t.get("events", [])):
        bits.append("wrote the vendor email")
    return "; ".join(bits) or "(not consulted: nothing it could change)"


def render() -> str:
    rules_all, rules = run(offline=True)
    live_all, live = run(replay_llm=str(CASSETTE))
    order = sorted(EXPECTED, key=lambda k: (k.split("-")[1], k))
    L = ["# Evaluation: every invoice, two separate runs", "",
         "Generated by `python scripts/evaluate.py`; do not edit by hand. Both runs process the 20 files in `data/invoices/` (17 distinct invoices; 3 are the same bill sent in "
         "two formats, which the duplicate check blocks) from an empty ledger.", "",
         "* **Rules only**: no model at all (`--offline`).",
         "* **LLM on**: the recorded live Grok run (`docs/live_runs/provided-invoices.cassette.jsonl`) replayed offline: the real model's answers, no network, no key, no cost. "
         "To check it yourself: `python main.py --replay-llm docs/live_runs/provided-invoices.cassette.jsonl --invoice_path data/invoices`.", "",
         "**Two kinds of label, kept apart.** *Brief* is what the assignment itself says should happen to eight invoices (independent of this code). *Label* is the expected "
         "outcome for all 17 that the developer wrote while building the system, so it guards against regressions but is **not** an independent test.", ""]

    def summary(title, outs, by):
        k, u = kpis(outs), llm_usage(outs)
        match = sum(same(by[i].status, EXPECTED[i]) for i in EXPECTED)
        brief = sum(same(by[i].status, s) for i, s in BRIEF.items())
        wrongly = sum(by[i].status == "PAID" and EXPECTED[i] != "PAID" for i in EXPECTED)
        cnt = {s: sum(by[i].status == s for i in EXPECTED) for s in ("PAID", "REJECT", "AWAITING")}
        return [f"## {title}", "", "| Measure | Result |", "|---|---|",
                f"| Matches the brief's stated outcome | {brief} of {len(BRIEF)} |", f"| Matches the developer's label | {match} of 17 |",
                f"| Wrongly paid (paid, but label says it should not be) | {wrongly} |",
                f"| Paid / rejected / sent to a person | {cnt['PAID']} / {cnt['REJECT']} / {cnt['AWAITING']} (+ {k.duplicates_blocked} duplicates blocked) |",
                f"| Model calls / tool calls | {u['calls']} / {u['tools']} |",
                f"| Tokens in / out | {u['tokens_in']:,} / {u['tokens_out']:,} |",
                f"| Cost | {'$%.4f (as reported by xAI when recorded)' % u['cost'] if u['cost'] is not None else '$0.00 (no model)'} |", ""]

    L += summary("Run 1: rules only", rules_all, rules)
    L += ["| Invoice | Vendor | Total | Brief says | Label | Decision | Match | Why |", "|---|---|---|---|---|---|---|---|"]
    for i in order:
        o = rules[i]
        L.append(f"| {i} | {cell(o.invoice.vendor or '-', 28)} | {o.invoice.currency} {o.invoice.total} | {BRIEF_WORDS.get(i, '(not specified)')} | {SHOW[EXPECTED[i]]} | "
                 f"{SHOW.get(o.status, o.status.lower())} | {'yes' if same(o.status, EXPECTED[i]) else '**NO**'} | {cell(o.approval.reasoning)} |")
    L.append("")
    L += summary("Run 2: LLM on (recorded live Grok run, replayed)", live_all, live)
    L += ["| Invoice | Decision | Match | What the model did | Model cost |", "|---|---|---|---|---|"]
    for i in order:
        o = live[i]
        c = o.llm.get("cost_ticks", 0) / 1e10
        L.append(f"| {i} | {SHOW.get(o.status, o.status.lower())} | {'yes' if same(o.status, EXPECTED[i]) else '**NO**'} | {model_part(o)} | {'$%.4f' % c if c else '-'} |")
    L.append("")
    agree = [i for i in order if same(rules[i].status, live[i].status)]
    diff = [i for i in order if i not in agree]
    L += ["## The two runs side by side", "",
          f"* Decisions identical on **{len(agree)} of 17** invoices" + ("" if not diff else "; they differ on: " + ", ".join(f"{i} (rules {rules[i].status.lower()}, model run {live[i].status.lower()})" for i in diff)) + ".",
          f"* The model did not change a single decision on these invoices. That is by design (it can only tighten a decision, and the provided invoices are clear-cut), so what it adds here is "
          f"a second opinion before each payment ({sum(1 for i in order if live[i].status == 'PAID')} paid), plain-English notes ({sum(bool(live[i].explanation) for i in order)}), vendor emails "
          f"({sum('wrote the vendor email' in model_part(live[i]) for i in order)}) and document reading where the rules were unsure. Where it changes outcomes is "
          "`data/self_correction/` (mistyped item names found by catalogue search), which is not part of this table.",
          "* Latency and cost of the model run are in `docs/live_runs/`; the rules-only run is milliseconds and free.", ""]
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/EVALUATION.md is out of date: run python scripts/evaluate.py (and re-record the live run if prompts changed)")
            return 1
        print("docs/EVALUATION.md is current")
        return 0
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
