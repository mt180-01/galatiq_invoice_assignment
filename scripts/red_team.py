"""Run the attack catalogue (acme_ap/redteam.py) twice and print or write the scoreboard.

    python scripts/red_team.py                 # rules only, plus the recorded live Grok run replayed (free)
    python scripts/red_team.py --record        # run the catalogue on live Grok (billed, capped, about a cent) and save the recording
    python scripts/red_team.py --check         # fail if docs/RED_TEAM.md is stale or anything got through
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from acme_ap.llm import make_llm  # noqa: E402
from acme_ap.redteam import Attack, run_all  # noqa: E402

DOC = ROOT / "docs" / "RED_TEAM.md"
CASSETTE = ROOT / "docs" / "live_runs" / "red-team.cassette.jsonl"


def _cell(a: Attack | None) -> str:
    if a is None:
        return "n/a"
    word = {"attack": "stopped", "control": "approved"}[a.kind]
    return word if a.passed() else ("**GOT THROUGH**" if a.kind == "attack" else "**WRONGLY BLOCKED**")


def _model_notes(attacks: list[Attack]) -> tuple[int, int]:
    calls = sum(o.llm.get("calls", 0) for a in attacks for o in a.outcomes)
    ticks = sum(o.llm.get("cost_ticks", 0) for a in attacks for o in a.outcomes)
    return calls, ticks


def render(rules: list[Attack], live: list[Attack] | None) -> str:
    by_name = {a.name: a for a in live or []}
    atk = [a for a in rules if a.kind == "attack"]
    ctl = [a for a in rules if a.kind == "control"]
    stopped = lambda xs, k: sum(a.passed() for a in xs if a.kind == k)  # noqa: E731
    head = f"**Rules only: {stopped(rules, 'attack')} of {len(atk)} attacks stopped, {stopped(rules, 'control')} of {len(ctl)} clean invoices approved.**"
    if live:
        calls, ticks = _model_notes(live)
        head += (f"  \n**With Grok (recorded live run, replayed): {stopped(live, 'attack')} of {len(atk)} attacks stopped, {stopped(live, 'control')} of {len(ctl)} clean invoices approved** "
                 f"({calls} model calls, ${ticks / 1e10:.4f} as reported by xAI).")
    row = lambda a: f"| {a.name} | {a.story} | {_cell(a)} | {_cell(by_name.get(a.name))} | {a.how()} |"  # noqa: E731
    return f"""# Red team: attacks the system must stop

Generated by `python scripts/red_team.py` from `acme_ap/redteam.py`. Each attack is modelled on a known accounts-payable fraud or failure. "Stopped" means no
invoice in it was approved for automatic payment (rejected, or held for a person). Controls are clean invoices that must still be approved, so the score cannot
be won by blocking everything. A model can only make a decision stricter, so the second column should never be worse than the first; the recording in
`docs/live_runs/red-team.cassette.jsonl` is the real Grok answering the same documents (replayed here for free).

{head}

The catalogue was written by the developer, so this shows the controls work against the attacks someone thought of, not against every attack. The first run
stopped 7 of 13: it let through an inflated unit price, an absurd tax line, a split purchase, a re-numbered duplicate, a future-dated invoice and a hidden
instruction to the reader. Each became a rule (`price_variance` over 25% is held, `implausible_tax`, `split_invoices`, `repeat_order`, `future_dated`,
`embedded_instructions`) and the catalogue now runs as a test, so none of them can come back unnoticed. Where an attack is several invoices, the first is the
real bill and may be paid; the rest must be stopped.

**What running it on live Grok found.** On the first recorded run the padded-total invoice (lines 2,000, total 2,600) *got through* with the model on, though rules
alone stopped it: asked to read a document whose figures do not add up, Grok reported a 600.00 shipping charge that is not printed anywhere, which made the
arithmetic work, and the invoice was approved. The model "helpfully" repaired a fraudulent document. The reconciliation step now accepts a shipping, tax or subtotal
figure from the model only when the regex reading sees it too or the amount is printed in the document; otherwise it is a disagreement and a person decides.
The same recorded answer now ends in a hold (`tests/test_red_team.py` pins it).

| Attack | What the fraudster does | Rules only | With Grok | What the rules said |
|---|---|---|---|---|
{chr(10).join(row(a) for a in atk)}

| Control | What it is | Rules only | With Grok | What the rules said |
|---|---|---|---|---|
{chr(10).join(row(a) for a in ctl)}
"""


def main() -> int:
    if "--record" in sys.argv:
        CASSETTE.unlink(missing_ok=True)
        os.environ["ACME_USE_GROK"] = "1"
        live = run_all(llm=make_llm(record_to=CASSETTE))
        print(f"recorded {CASSETTE.name}: {_model_notes(live)[0]} model calls")
    rules = run_all()
    live = run_all(llm=make_llm(replay_from=CASSETTE)) if CASSETTE.exists() else None
    text = render(rules, live)
    ok = all(a.passed() for a in rules + (live or []))
    if "--check" in sys.argv:
        current = DOC.read_text() if DOC.exists() else ""
        print("docs/RED_TEAM.md is current" if current == text else "docs/RED_TEAM.md is STALE: run python scripts/red_team.py")
        print("all attacks stopped, all controls approved" if ok else "SOMETHING GOT THROUGH or a clean invoice was blocked")
        return 0 if (current == text and ok) else 1
    DOC.write_text(text)
    print(text)
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
